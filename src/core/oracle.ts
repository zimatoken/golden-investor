// src/core/oracle.ts

import type { MarketState } from '../data/manualMarket';
import type { PlanRow } from '../types/market';

/**
 * Уровень уверенности рекомендации.
 */
export type OracleLevel = 'act' | 'wait' | 'danger';

/**
 * Результат работы оракула.
 */
export interface OracleAdvice {
  level: OracleLevel;
  icon: string;
  title: string;           // Заголовок («Совет на сентябрь 2026»)
  headline: string;        // Главная мысль (1 предложение)
  reasoning: string[];     // Логика (2-4 пункта)
  action?: string;         // Что делать («Проверь карту →»)
  warning?: string;        // Предупреждение
}

const MONTH_NAMES = [
  'январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
  'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь',
];

function getCurrentMonth(): string {
  const m = new Date().getMonth();
  return MONTH_NAMES[m];
}

function formatPct(v: number, signed = true): string {
  const sign = signed && v > 0 ? '+' : '';
  return `${sign}${v.toFixed(2)}%`;
}

/**
 * Главный движок анализа. 12 правил.
 *
 * Принцип формулировок v4:
 * — описываем условия сценария, а не даём приказ;
 * — рядом с выгодой всегда называем риск;
 * — не используем слова «бесполезно», «сгорают», «право чаще».
 */
export function getOracleAdvice(
  market: MarketState,
  plan: PlanRow[] = []
): OracleAdvice {
  const month = getCurrentMonth();

  // Производные метрики
  const realDeposit = market.depositRate - market.inflation;
  const realKeyRate = market.keyRate - market.inflation;
  const ofzSpread = market.ofz10y - market.depositRate;

  // Правило 1: Ставка ниже инфляции — реальная доходность отрицательная
  if (market.keyRate < market.inflation) {
    return {
      level: 'danger',
      icon: '🔥',
      title: `Совет на ${month} 2026`,
      headline: `Реальная доходность отрицательная: ставка ${market.keyRate}% ниже инфляции ${market.inflation}%.`,
      reasoning: [
        `Реальная ключевая ставка: ${formatPct(realKeyRate)} — отрицательная.`,
        `Реальная ставка вклада: ${formatPct(realDeposit)}. Вклад не компенсирует инфляцию.`,
        `При таких условиях покупательная способность денег в номинальных активах снижается.`,
      ],
      action: `Проверь «🗺 Карта» — есть ли там сценарий на случай устойчивой инфляции`,
      warning: `В такой среде классические депозиты и длинные ОФЗ обычно проигрывают. Стоит рассмотреть защитные активы.`,
    };
  }

  // Правило 2: Реальная ставка вклада < 0
  if (realDeposit < 0) {
    return {
      level: 'danger',
      icon: '⚠️',
      title: `Совет на ${month} 2026`,
      headline: `Ставка вклада ${market.depositRate}% ниже инфляции ${market.inflation}% — реальная доходность отрицательная.`,
      reasoning: [
        `Реальная доходность вклада: ${formatPct(realDeposit)}. Покупательная способность денег на вкладе снижается.`,
        `Ключевая ставка: ${market.keyRate}% — реальная ${formatPct(realKeyRate)}.`,
        `ОФЗ 10л: ${market.ofz10y}% — реальная ${formatPct(market.ofz10y - market.inflation)}.`,
      ],
      action: `Рассмотри сценарии в «🗺 Карта» — вклад как резерв, но не как защита от инфляции`,
      warning: `Вклад остаётся инструментом для краткосрочной ликвидности. Но при такой инфляции он не защищает капитал.`,
    };
  }

  // Правило 3: ОФЗ доходность выше вклада на 3%+ — возможен сценарий ОФЗ
  if (ofzSpread >= 3 && realKeyRate > 0) {
    return {
      level: 'act',
      icon: '🟢',
      title: `Совет на ${month} 2026`,
      headline: `10-летние ОФЗ (${market.ofz10y}%) дают на ${formatPct(ofzSpread)} больше вклада (${market.depositRate}%).`,
      reasoning: [
        `Разница между доходностью к погашению ОФЗ и ставкой вклада: ${formatPct(ofzSpread)}.`,
        `Ключевая ставка ${market.keyRate}% — реальная ${formatPct(realKeyRate)}.`,
        `Если ЦБ снизит ставку — цена длинных ОФЗ вырастет. Но если ставка вырастет — цена упадёт.`,
      ],
      action: plan.length > 0
        ? `Открой «🗺 Карта» — если там записан сценарий на снижение ставки, сверься с планом`
        : `Открой «🗺 Карта» и запиши сценарий: «если ставка начнёт снижаться — рассмотреть длинные ОФЗ»`,
      warning: `Если ставка не упадёт — останется только купон (${market.keyRate}% годовых). Длинные ОФЗ — это ставка на снижение ставки, а не «просто высокая доходность».`,
    };
  }

  // Правило 4: ОФЗ немного выше вклада — сценарий возможен с оговоркой
  if (ofzSpread >= 1.5 && realKeyRate > 0) {
    return {
      level: 'act',
      icon: '🟢',
      title: `Совет на ${month} 2026`,
      headline: `ОФЗ (${market.ofz10y}%) немного выше вклада (${market.depositRate}%) — разница ${formatPct(ofzSpread)}.`,
      reasoning: [
        `Разница: ${formatPct(ofzSpread)} — есть смысл рассмотреть ОФЗ, но она небольшая.`,
        `Реальная ключевая ставка: ${formatPct(realKeyRate)} — положительная.`,
        `Если ставка останется высокой — тело облигации не вырастет, будет только купон.`,
      ],
      action: `Сверься со своим планом в «🗺 Карта»`,
      warning: `Разница небольшая. Убедись, что готов держать ОФЗ долго (3+ года) и выдержишь просадку, если ставка вырастет.`,
    };
  }

  // Правило 5: Вклад существенно выгоднее ОФЗ — не торопиться
  if (ofzSpread <= -1 && market.depositRate > market.inflation) {
    return {
      level: 'wait',
      icon: '🟡',
      title: `Совет на ${month} 2026`,
      headline: `Вклад (${market.depositRate}%) даёт больше ОФЗ (${market.ofz10y}%).`,
      reasoning: [
        `Разница: ${formatPct(ofzSpread)} — ОФЗ проигрывают по текущей доходности к погашению.`,
        `Реальная ставка вклада: ${formatPct(realDeposit)} — покупательная способность сохраняется.`,
        `У ОФЗ есть риск просадки при росте ставки — при такой разнице он не компенсируется.`,
      ],
      action: `Оставайся во вкладе. Дождись, пока доходность ОФЗ станет интереснее`,
      warning: `Не перекладывайся в ОФЗ только потому, что «это долгосрочный инструмент». Сравнивай доходность и риск.`,
    };
  }

  // Правило 6: Высокая инфляция (>8%), ставка держит её
  if (market.inflation > 8 && market.keyRate > market.inflation) {
    return {
      level: 'wait',
      icon: '🟡',
      title: `Совет на ${month} 2026`,
      headline: `Инфляция ${market.inflation}% — ЦБ держит ставку ${market.keyRate}% для охлаждения экономики.`,
      reasoning: [
        `Реальная ключевая ставка: ${formatPct(market.keyRate - market.inflation)} — положительная.`,
        `Деньги в депозите не сгорают, но и не растут быстро.`,
        `В такой среде ЦБ обычно не снижает ставку — ждём сигналов замедления инфляции.`,
      ],
      action: `Оставайся в депозите. Следи за заседаниями ЦБ`,
      warning: `При инфляции ${market.inflation}% рискованные активы (длинные ОФЗ, акции) могут быть волатильны. Не торопись.`,
    };
  }

  // Правило 7: Низкая инфляция (<5%) — окно для длинных ОФЗ
  if (market.inflation < 5 && market.keyRate <= market.ofz10y) {
    return {
      level: 'act',
      icon: '🟢',
      title: `Совет на ${month} 2026`,
      headline: `Инфляция ${market.inflation}%, ставка ${market.keyRate}% — условия для длинных ОФЗ.`,
      reasoning: [
        `Низкая инфляция + ставка ниже доходности ОФЗ — типичный сценарий для длинных ОФЗ.`,
        `Купон + возможный рост тела дают полную доходность выше вклада.`,
        `Но: рынок может быть уже «нагрет» — нужна проверка через данные ЦБ.`,
      ],
      action: `Открой «🗺 Карта» — сверься со сценарием на снижение ставки`,
      warning: `Если ставка резко вырастет — цена длинных ОФЗ упадёт. Проверь блок «Чувствительность к ставке» выше.`,
    };
  }

  // Правило 8: Ключевая ставка выше 15% — потенциально пик цикла
  if (market.keyRate >= 15) {
    return {
      level: 'act',
      icon: '🟢',
      title: `Совет на ${month} 2026`,
      headline: `Ставка ${market.keyRate}% — на высоком уровне.`,
      reasoning: [
        `Вклад даёт ${market.depositRate}% — максимальная доходность в коротком горизонте.`,
        `Длинные ОФЗ выгоднее покупать, когда ставка уже начала снижаться.`,
        `Когда ЦБ даст первые сигналы снижения — можно рассматривать длинные ОФЗ.`,
      ],
      action: `Держи деньги в коротком депозите (3-6 мес). Дождись сигналов ЦБ`,
      warning: `Длинные ОФЗ сейчас — ставка на скорое снижение ставки. Если она ещё вырастет — цена упадёт. Проверь «Чувствительность к ставке».`,
    };
  }

  // Правило 9: Ключевая ставка ниже 10% — низкие ставки, активы интереснее
  if (market.keyRate < 10 && market.inflation < 6) {
    return {
      level: 'act',
      icon: '🟢',
      title: `Совет на ${month} 2026`,
      headline: `Ставка ${market.keyRate}% — низкая. Реальная доходность вклада: ${formatPct(realDeposit)}.`,
      reasoning: [
        `При ставке ${market.keyRate}% вклад даёт реальную доходность ${formatPct(realDeposit)}.`,
        `В такой среде исторически растут длинные ОФЗ и другие активы с длинной дюрацией.`,
        `Инфляция ${market.inflation}% — под контролем.`,
      ],
      action: `Рассмотри длинные ОФЗ, но проверь свой горизонт (3+ года)`,
      warning: `Низкая ставка вклада — не повод «срочно перекладываться». Проверь свой Investment Policy: горизонт, просадку, ликвидность.`,
    };
  }

  // Правило 10: Золото как защитный актив при высокой инфляции
  if (market.inflation > 7 && market.goldPrice > 0) {
    return {
      level: 'wait',
      icon: '🥇',
      title: `Совет на ${month} 2026`,
      headline: `Инфляция ${market.inflation}% — золото может выполнять защитную функцию.`,
      reasoning: [
        `Золото исторически используется как страховка от инфляции, но работает на длинном горизонте (10+ лет).`,
        `Текущая цена: ${market.goldPrice.toLocaleString('ru-RU')} ₽/грамм.`,
        `Золото не платит купон — доход формируется только за счёт изменения цены.`,
      ],
      action: `Рассмотри ОМС (от 0,1 грамма) или БПИФ золота`,
      warning: `Золото — страховка, а не двигатель дохода. Не вкладывай в него всё. В краткосрочной перспективе золото часто не защищает от инфляции.`,
    };
  }

  // Правило 11: Разброс ставок между банками
  if (market.depositRate > 0) {
    return {
      level: 'wait',
      icon: '🏦',
      title: `Совет на ${month} 2026`,
      headline: `Средняя ставка по вкладам: ${market.depositRate}%. Проверь разброс между банками.`,
      reasoning: [
        `Разные банки предлагают разные ставки — разница может доходить до 1,5 п.п.`,
        `За год это ощутимая сумма: например, 15 000 ₽ на 1 млн ₽.`,
        `Проверь таблицу банков ниже.`,
      ],
      action: `Открой таблицу банков → выбери максимальную ставку`,
      warning: `Не держи всё в одном банке. Лимит страховки АСВ — 1,4 млн ₽ на банк.`,
    };
  }

  // Правило 12 (fallback): нет явных сигналов
  return {
    level: 'wait',
    icon: '😴',
    title: `Совет на ${month} 2026`,
    headline: `Явных сигналов нет. Условия в норме.`,
    reasoning: [
      `Ставка: ${market.keyRate}%, инфляция: ${market.inflation}%.`,
      `ОФЗ 10л: ${market.ofz10y}%, вклад: ${market.depositRate}%.`,
      `Соотношения в норме — не время для резких решений.`,
    ],
    action: `Следующий сигнал — заседание ЦБ ${market.nextCBDate}`,
    warning: undefined,
  };
}